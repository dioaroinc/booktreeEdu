    public function run(): void
    {
        $now = date('Y-m-d H:i:s');

        // 데모 과정은 비공개 처리 (관리자에서 삭제 가능)
        $this->db->table('courses')
            ->whereIn('title', ['신규원장교육', '지점SW 사용교육', '보수교육'])
            ->update(['is_active' => 0, 'updated_at' => $now]);

        // 분류 → 교육과정
        $courseIds = [];
        $order     = 1;
        foreach (self::COURSES as $title => [$icon, $color, $subtitle, $description]) {
            $existing = $this->db->table('courses')->where('title', $title)->get()->getRowArray();
            if ($existing) {
                $courseIds[$title] = (int) $existing['id'];
                continue;
            }
            $this->db->table('courses')->insert([
                'title'       => $title,
                'subtitle'    => $subtitle,
                'description' => $description,
                'icon'        => $icon,
                'color'       => $color,
                'sort_order'  => $order++,
                'is_active'   => 1,
                'created_at'  => $now,
                'updated_at'  => $now,
            ]);
            $courseIds[$title] = (int) $this->db->insertID();
        }

        // 강의 (자료실 번호가 여러 개면 번호마다 한 강의씩, 제목에 (1/3) 식으로 표시)
        $sort = [];
        foreach (self::VIDEOS as [$category, $refs, $title, $dates, $lecturer, $required]) {
            $refList  = array_map('trim', explode(',', $refs));
            $dateList = array_map('trim', explode(',', $dates));
            $total    = count($refList);

            foreach ($refList as $i => $ref) {
                if ($this->db->table('lessons')->where('ref_no', $ref)->countAllResults() > 0) {
                    continue; // 이미 등록됨
                }

                $courseId        = $courseIds[$category];
                $sort[$courseId] = ($sort[$courseId] ?? 0) + 1;

                $this->db->table('lessons')->insert([
                    'course_id'     => $courseId,
                    'section_id'    => null,
                    'title'         => $total > 1 ? sprintf('%s (%d/%d)', $title, $i + 1, $total) : $title,
                    'description'   => '',
                    'ref_no'        => $ref,
                    'lecturer'      => $lecturer,
                    'lecture_date'  => $dateList[$i] ?? $dateList[0],
                    'is_required'   => $required ? 1 : 0,
                    'video_type'    => VIDEO_TYPE_YOUTUBE,
                    'video_url'     => '',
                    'video_file'    => null,
                    'duration_min'  => 0,
                    'pass_score'    => 80,
                    'require_video' => 1,
                    'sort_order'    => $sort[$courseId],
                    'is_active'     => 1,
                    'created_at'    => $now,
                    'updated_at'    => $now,
                ]);
            }
        }
    }
